
CREATE TABLE problems (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(200) NOT NULL,
    slug VARCHAR(220) NOT NULL UNIQUE,
    description TEXT NOT NULL,
    difficulty VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL,
    problem_constraints TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_problem_difficulty
    ON problems(difficulty);

CREATE INDEX idx_problem_status
    ON problems(status);


CREATE TABLE topics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE
);


CREATE TABLE test_cases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    problem_id BIGINT NOT NULL,
    input TEXT NOT NULL,
    expected_output TEXT NOT NULL,
    hidden BOOLEAN NOT NULL DEFAULT FALSE,
    sequence_order INTEGER NOT NULL,

    CONSTRAINT fk_test_case_problem
        FOREIGN KEY (problem_id)
        REFERENCES problems(id)
        ON DELETE CASCADE,

    CONSTRAINT uk_test_case_problem_order
        UNIQUE (problem_id, sequence_order)
);


CREATE TABLE problem_topics (
    problem_id BIGINT NOT NULL,
    topic_id BIGINT NOT NULL,

    PRIMARY KEY (problem_id, topic_id),

    CONSTRAINT fk_problem_topics_problem
        FOREIGN KEY (problem_id)
        REFERENCES problems(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_problem_topics_topic
        FOREIGN KEY (topic_id)
        REFERENCES topics(id)
        ON DELETE CASCADE
);

CREATE INDEX idx_problem_topics_topic
    ON problem_topics(topic_id);
