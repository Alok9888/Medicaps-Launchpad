-- V3: Question Bank Upgrade - Add new columns and tables for full question bank features

-- 1. Add new columns to problems
ALTER TABLE problems
    ADD COLUMN IF NOT EXISTS input_format TEXT,
    ADD COLUMN IF NOT EXISTS output_format TEXT,
    ADD COLUMN IF NOT EXISTS time_limit_ms INT NOT NULL DEFAULT 2000,
    ADD COLUMN IF NOT EXISTS memory_limit_kb INT NOT NULL DEFAULT 262144,
    ADD COLUMN IF NOT EXISTS comparator VARCHAR(20) NOT NULL DEFAULT 'TRIM_LINES',
    ADD COLUMN IF NOT EXISTS float_epsilon NUMERIC(12,10),
    ADD COLUMN IF NOT EXISTS content_revision INT NOT NULL DEFAULT 1,
    ADD COLUMN IF NOT EXISTS created_by BIGINT,
    ADD COLUMN IF NOT EXISTS updated_by BIGINT,
    ADD COLUMN IF NOT EXISTS published_at TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS row_version BIGINT NOT NULL DEFAULT 0;

-- Backfill published_at for already published problems
UPDATE problems
SET published_at = created_at
WHERE status = 'PUBLISHED' AND published_at IS NULL;

-- Add constraint for comparator values
ALTER TABLE problems
    ADD CONSTRAINT chk_problem_comparator CHECK (comparator IN ('EXACT', 'TRIM_LINES', 'FLOAT_TOLERANCE'));

-- Add indexes
CREATE INDEX IF NOT EXISTS idx_problem_status_difficulty ON problems(status, difficulty);

-- 2. Add explanation column to test_cases
ALTER TABLE test_cases
    ADD COLUMN IF NOT EXISTS explanation TEXT;

-- 3. Create languages table
CREATE TABLE IF NOT EXISTS languages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    judge0_language_id INT NOT NULL,
    file_extension VARCHAR(20) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

-- 4. Create problem_languages table
CREATE TABLE IF NOT EXISTS problem_languages (
    problem_id BIGINT NOT NULL REFERENCES problems(id) ON DELETE CASCADE,
    language_id BIGINT NOT NULL REFERENCES languages(id) ON DELETE CASCADE,
    starter_code TEXT,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    PRIMARY KEY (problem_id, language_id)
);

-- 5. Create companies table
CREATE TABLE IF NOT EXISTS companies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200) NOT NULL UNIQUE
);

-- 6. Create problem_companies table
CREATE TABLE IF NOT EXISTS problem_companies (
    problem_id BIGINT NOT NULL REFERENCES problems(id) ON DELETE CASCADE,
    company_id BIGINT NOT NULL REFERENCES companies(id) ON DELETE CASCADE,
    frequency INT,
    PRIMARY KEY (problem_id, company_id)
);

CREATE INDEX IF NOT EXISTS idx_problem_companies_company ON problem_companies(company_id);

-- 7. Create problem_hints table
CREATE TABLE IF NOT EXISTS problem_hints (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    problem_id BIGINT NOT NULL REFERENCES problems(id) ON DELETE CASCADE,
    hint_order INT NOT NULL,
    content TEXT NOT NULL,
    UNIQUE (problem_id, hint_order)
);